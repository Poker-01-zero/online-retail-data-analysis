-- 【附：为什么 Group By 报 1055 是好事】
--   only_full_group_by 模式要求：SELECT 里的每个非聚合列，必须要么出现在
--   GROUP BY 中，要么能被 GROUP BY 的列函数式决定。
--   若关掉它，当分组粒度不够时 MySQL 会从组内【随意挑一行】返回，
--   你会得到一个每次执行可能不同、却不报错的数字。
--   正确做法是补全 GROUP BY 或改写查询，而不是 SET sql_mode = ''。
