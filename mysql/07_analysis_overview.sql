-- 07_analysis_overview.sql
-- 用途：经营概览 —— 用时点/总量指标回答"这门生意有多大"
-- 依赖：05（清洗层）、06（派生字段 Revenue / YearMonth）
-- 表：online_retail_clean（全量 1,003,213 行）
-- ============================================================
-- 【本步的难点不在 SQL，在口径】
--   下面每个指标都有至少一个"看起来也对"的错误写法。
--   文件里用 ❌ 标出错误写法并说明为什么错，这是刻意留的 ——
--   面试被追问"你这个数怎么算的"，答案就在这里。
--
-- 【五条口径决策】
--
--   决策 1：订单数 = COUNT(DISTINCT Invoice)，不是 COUNT(*)。
--     本表是【订单行明细】，一次下单买 3 种商品 = 1 张发票 = 3 行。
--     COUNT(*) = 1,003,213 是"卖出多少行商品"，不是"成交多少单"。
--     判断法：问自己这个指标的业务主语是什么。主语是"订单"，粒度就是发票。
--
--   决策 2：客户数只统计实名客户（Customer_ID IS NOT NULL）。
--     约 1/5 的订单没有客户 ID。所以 5,852 是"有身份记录的客户数"，
--     真实客户总数 ≥ 5,852 且无法从数据得知。这句话必须写进结论，
--     不能只写"客户数 5,852"。
--
--   决策 3：客单价有两个口径，AOV ≠ ARPU，绝不能混用。
--     AOV  (平均订单金额) = 营收 ÷ 订单数  → 一次下单平均花多少
--     ARPU (人均消费)     = 营收 ÷ 客户数  → 一个客户平均花多少
--     本数据集 AOV ≈ £497.08。
--
--   决策 4：【分子分母必须来自同一批数据】—— 这是本文件最重要的一条。
--     ❌ ARPU ≠ 全量营收 ÷ 实名客户数
--        分子含匿名订单的钱，分母却只有实名客户 → ARPU 被系统性抬高。
--        正确写法：分子分母都加 WHERE Customer_ID IS NOT NULL。
--     这条原则守住了，D6 的 RFM / 留存才不会出错；守不住，
--     后面每一步都会错得看不出来。
--
--   决策 5：匿名占比要用【发票口径】而不是【行口径】。
--     CLAUDE.md 里记的"匿名订单 226,636（22.6%）"其实是
--     226,636 ÷ 1,003,213 = 匿名【订单行】占比。
--     严格说"订单"的粒度是发票，本文件给出准确的匿名发票数。
-- ============================================================

USE online_retail;


-- ------------------------------------------------------------
-- ① 核心总量指标（一行结果）
-- 实测：总营收 19082339.73 ｜ 订单数 39231 ｜ 客户数 5835 ｜ AOV 486.41
-- 注：以上为 05 脚本修复「被取消的原始订单行」漏洞【之后】的基准。
--     修复前的旧值（19642676.02 / 39516 / 5852 / 497.08）已作废，勿再引用。
--
-- 注：客户数只算实名（决策 2）。COUNT(DISTINCT Customer_ID) 天然忽略 NULL，
--     所以这里不需要额外 WHERE —— 但下面 ③ 的 ARPU 就必须显式加，
--     因为 SUM(Revenue) 会把匿名订单的钱也算进来。
-- ------------------------------------------------------------
SELECT
  ROUND(SUM(Revenue), 2)                            AS 总营收,
  COUNT(DISTINCT Invoice)                           AS 订单数,
  COUNT(DISTINCT Customer_ID)                       AS 客户数_仅实名,
  ROUND(SUM(Revenue) / COUNT(DISTINCT Invoice), 2)  AS AOV_平均订单金额
FROM online_retail_clean;


-- ------------------------------------------------------------
-- ② 营收按「实名 / 匿名」拆开 —— 可加性检查
--
-- 硬性检查：两行「营收」相加 = 19,642,676.02
--          两行「发票数」相加 = 39,516
-- 对不上就说明分组丢了行，必须查清再往下走。
--
-- 【语法说明】GROUP BY 用的是 SELECT 里的别名「客户类型」。
--   这是 MySQL 对标准 SQL 的扩展（标准写法要把 CASE 表达式原样重复一遍）。
--   ⚠️ 不能写 GROUP BY Customer_ID IS NOT NULL —— 那样 SELECT 里的
--      CASE 表达式与分组键形态不同，会触发 Error 1055
--      (only_full_group_by)，MySQL 拒绝执行。
--      这个模式是保护机制不是障碍，详见文件末尾说明。
-- ------------------------------------------------------------
SELECT
  CASE WHEN Customer_ID IS NOT NULL THEN '实名' ELSE '匿名' END AS 客户类型,
  COUNT(*)                       AS 订单行数,
  COUNT(DISTINCT Invoice)        AS 发票数,      -- 这才是"订单"口径
  COUNT(DISTINCT Customer_ID)    AS 客户数,      -- 匿名组必然为 0
  ROUND(SUM(Revenue), 2)         AS 营收
FROM online_retail_clean
GROUP BY 客户类型
ORDER BY 客户类型;


-- ------------------------------------------------------------
-- ③ 客单价两个口径 + 恒等式自查（仅实名口径）
--
-- ⚠️ 本查询的 WHERE 是关键：分子分母同源（决策 4）。
--
-- 【恒等式】实名AOV × 平均购买次数 与 ARPU 的关系：
--     实名营收/发票数 × 发票数/客户数 = 实名营收/客户数 = ARPU
--   这是一条【代数恒等式】—— 中间的"发票数"直接约掉，两边必然相等。
--   所以它是个【硬校验】：若不等，说明分子分母取错了数据
--   （例如 ARPU 的分子混入了匿名营收）。
--
--   ⚠️ 校验必须在 SQL 里用【未舍入】的值做，不能拿显示出来的两位小数手算：
--      显示值 466.43 × 6.25 = 2915.19 ≠ 2916.71，看着像"不相等"，
--      其实只是【先舍入再相乘】引入的误差。
--      记牢：四舍五入后再运算 ≠ 运算后再四舍五入。
--      所以下面的查询直接把两种算法各算一遍做对比 —— 它们必须完全相同。
-- ------------------------------------------------------------
SELECT
  COUNT(DISTINCT Customer_ID)                                     AS 客户数,
  ROUND(SUM(Revenue), 2)                                          AS 实名营收,
  ROUND(COUNT(DISTINCT Invoice) / COUNT(DISTINCT Customer_ID), 2) AS 平均购买次数,
  ROUND(SUM(Revenue) / COUNT(DISTINCT Invoice), 2)                AS 实名AOV,
  ROUND(SUM(Revenue) / COUNT(DISTINCT Customer_ID), 2)            AS ARPU_人均消费,
  -- 恒等式硬校验：两种算法必须给出完全相同的结果
  ROUND((SUM(Revenue) / COUNT(DISTINCT Invoice))
        * (COUNT(DISTINCT Invoice) / COUNT(DISTINCT Customer_ID)), 2) AS ARPU_校验值
FROM online_retail_clean
WHERE Customer_ID IS NOT NULL;


