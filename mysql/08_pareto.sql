-- ============================================================
-- 08_pareto.sql
-- 用途：帕累托分析 —— 客户消费集中度（少数客户是否贡献了大部分营收）
-- 依赖：05（清洗层）、06（派生字段 Revenue）
-- 表：online_retail_clean
-- ============================================================
-- 【帕累托是什么】
--   即"80/20 法则"。放在客户分析里就一句话：
--     是不是少数客户贡献了大部分营收？集中到什么程度？
--   这一问的意义在于它直接决定运营资源往哪投：
--     若营收高度集中 → 重心是"保住头部客户"；
--     若高度分散     → 重心才是"广撒网拉新"。
--
-- 【三条必须写明的口径】
--
--   1) 只看【实名客户】，且分子分母都只算实名营收。
--      匿名订单行占 22.74%、营收占 13.49%，但无法归属到任何客户。
--      若把匿名营收混进分子、或用全量营收当分母，占比会失真
--      （实测：分母用全量时，十组占比加起来只有 86.5%，不是 100%）。
--      ⚠️ 这是本项目反复踩的同一个坑（ARPU 一次、本文件一次）：
--         任何改写查询的动作，都要重新确认 WHERE Customer_ID IS NOT NULL 还在。
--         尤其是把查询搬进 CTE 或子查询时 —— 实测就漏过一次。
--      ⚠️ 还有一个更隐蔽的后果：匿名订单聚合后，
--         会成为全表"消费额最高"的那一个假客户（£2,574,108.05，排第 1），
--         从而被分进"最优质客户"那一组，污染整个分箱。
--
--   2) 分箱按【人数】等分，不按【金额】等分。
--      NTILE(n) 把客户按消费额从高到低排序后平均切成 n 份，每份人数相同。
--      只有这样才能回答"前 10% 的人贡献多少"这种业务问题。
--      （按金额等分得到的是另一种分位，业务上不好解释。）
--
--   3) 占比的分母是【实名营收合计 16,508,231.68】，
--      不是【全量营收 19,082,339.73】。同样是分子分母必须同源。
--
-- 【关键数字（2026-10-15 实测）】
--   实名客户数 5,835 ｜ 实名营收 £16,508,231.68
--   Top 10% 客户（584 人）贡献 63.18% 营收
--   Top 30% 客户（1,752 人）贡献 84.66% 营收
--   最低 50% 客户（2,918 人）仅贡献 6.60% 营收
-- ============================================================

USE online_retail;


-- ------------------------------------------------------------
-- ① 地基：每个客户花了多少钱、买了几次
--    后面所有分箱的输入，必须先对账。
--    检查点：客户行数 5835 ｜ 消费额合计 16508231.68
-- ------------------------------------------------------------
SELECT
  Customer_ID,
  ROUND(SUM(Revenue), 2)   AS 消费金额,
  COUNT(DISTINCT Invoice)  AS 消费次数
FROM online_retail_clean
WHERE Customer_ID IS NOT NULL        -- ← 漏掉这一句，匿名订单会聚成一个"超级客户"
GROUP BY Customer_ID
ORDER BY 消费金额 DESC;


-- ============================================================
-- ② 四分位（每份约 25% 客户）—— 先看粗粒度
-- ============================================================
WITH jin_e AS (
  SELECT Customer_ID, SUM(Revenue) AS pay
  FROM online_retail_clean
  WHERE Customer_ID IS NOT NULL
  GROUP BY Customer_ID
),
fenzu AS (
  SELECT Customer_ID, pay, NTILE(4) OVER (ORDER BY pay DESC) AS zu_hao
  FROM jin_e
)
SELECT
  zu_hao                                                AS 组号,
  COUNT(*)                                              AS 客户数,
  ROUND(SUM(pay), 2)                                    AS 营收,
  ROUND(SUM(pay) / (SELECT SUM(pay) FROM jin_e) * 100, 2) AS 营收占比
FROM fenzu
GROUP BY zu_hao
ORDER BY zu_hao;

-- 实测：Top 25%（1459 人）贡献 81.14%


-- ============================================================
-- ③ 十分位 + 累计占比 —— 帕累托曲线的数据点
--
--    「累计占比」用窗口函数 SUM() OVER (ORDER BY 组号) 求得：
--    它把前 N 组的营收累加，正是"前 N 成客户一共贡献了多少"。
--    这就是帕累托曲线的纵轴，也是"Top 10% 客户贡献 X%"这句话的出处。
--
--    检查点：最后一组的累计占比必须恰好 = 100.00
-- ============================================================
WITH jin_e AS (
  SELECT Customer_ID, SUM(Revenue) AS pay
  FROM online_retail_clean
  WHERE Customer_ID IS NOT NULL
  GROUP BY Customer_ID
),
fenzu AS (
  SELECT Customer_ID, pay, NTILE(10) OVER (ORDER BY pay DESC) AS zu_hao
  FROM jin_e
),
huizong AS (
  SELECT zu_hao, COUNT(*) AS 客户数, SUM(pay) AS 营收
  FROM fenzu
  GROUP BY zu_hao
)
SELECT
  zu_hao                                                       AS 组号,
  客户数,
  ROUND(营收, 2)                                               AS 营收,
  ROUND(营收 / (SELECT SUM(pay) FROM jin_e) * 100, 2)          AS 营收占比,
  ROUND(SUM(营收) OVER (ORDER BY zu_hao)
        / (SELECT SUM(pay) FROM jin_e) * 100, 2)               AS 累计占比
FROM huizong
ORDER BY zu_hao;

-- 实测：
--   组号 客户数   营收            营收占比  累计占比
--    1    584   10,429,897.63     63.18     63.18   ← Top 10% → 63.18%
--    2    584    2,235,859.41     13.54     76.72
--    3    584    1,310,198.68      7.94     84.66   ← Top 30% → 84.66%
--    4    584      851,782.93      5.16     89.82
--    5    584      591,201.00      3.58     93.40   ← Top 50% → 93.40%
--    6    583      418,360.33      2.53     95.94
--    7    583      286,201.41      1.73     97.67
--    8    583      197,245.55      1.19     98.86
--    9    583      125,888.42      0.76     99.63
--   10    583       61,596.32      0.37    100.00
--   合计 5835   16,508,231.68    100.00


-- ============================================================
-- ④ 辅助视角：购买次数分布 —— 回答"集中是怎么形成的"
--    帕累托只说"钱集中在少数人手里"，不说"为什么"。
--    这一步补上后半截。
-- ============================================================
SELECT
  CASE WHEN n >= 100 THEN '5. 100 次以上'
       WHEN n >= 50  THEN '4. 50-99 次'
       WHEN n >= 20  THEN '3. 20-49 次'
       WHEN n >= 5   THEN '2. 5-19 次'
       WHEN n >= 2   THEN '1. 2-4 次'
       ELSE               '0. 仅 1 次' END   AS 购买次数段,
  COUNT(*)                                  AS 客户数,
  ROUND(COUNT(*) / 5835 * 100, 2)           AS 客户占比,
  ROUND(SUM(s), 2)                          AS 营收,
  ROUND(SUM(s) / 16508231.68 * 100, 2)      AS 营收占比
FROM (
  SELECT Customer_ID, SUM(Revenue) AS s, COUNT(DISTINCT Invoice) AS n
  FROM online_retail_clean
  WHERE Customer_ID IS NOT NULL
  GROUP BY Customer_ID
) t
GROUP BY 购买次数段
ORDER BY 购买次数段;

-- 实测：
--   仅 1 次     1609 人（27.57%）→ 营收占比  3.35%
--   2-4 次      2096 人（35.92%）→ 营收占比 11.92%
--   5-19 次     1808 人（30.99%）→ 营收占比 37.56%
--   20-49 次     269 人（ 4.61%）→ 营收占比 22.10%
--   50-99 次      33 人（ 0.57%）→ 营收占比  7.95%
--   100 次以上    20 人（ 0.34%）→ 营收占比 17.11%


-- ============================================================
-- 【分析结论】
-- ============================================================
--
-- 一、营收高度集中，且集中由「高频复购」而非「偶发大单」驱动
--
--    实名口径下，Top 10%（584 人）贡献 63.18% 营收，Top 30% 贡献 84.66%；
--    而最低 50%（2,918 人）仅贡献 6.60%。
--
--    头部并非靠几笔运气单撑起来的 —— Top 10 客户中多位购买次数超过 100 次
--    （14911 达 370 次、12748 达 316 次、18102 达 145 次），
--    说明高营收来自长期、稳定的重复采购。
--
--    → 所以：运营资源不应平均分摊到全部客户。
--      抓头部的手段是"维护长期供应关系"，而不是"促销冲大单"。
--
-- 二、集中度是双刃剑：它既是机会，也是风险
--
--    63% 的营收压在 10% 的客户身上 —— 这批人一旦流失或转投他处，
--    营收会直接蒸发六成。因此"维护头部"的本质是【风险管理】，而非增长策略。
--
--    → 所以：头部客户应纳入重点跟踪（流失预警），而不只是被当作业绩来源。
--
-- 三、长尾贡献极低，但这不等于"只做头部"
--
--    一次性客户 1,609 人（27.57%）只贡献 3.35% 营收；
--    最低 50% 客户（2,918 人）只贡献 6.60%。
--    这组数字反映的是【首购之后的留存环节有问题】，而不是"客户不值得要"。
--
--    → 所以：问题不在"要不要拉新"，而在"拉来之后留不留得住"。
--
-- 四、本分析的边界（分析结论必须声明自己回答不了什么）
--
--    · 口径：以上均为【实名客户】口径。匿名订单行占 22.74%、营收占 13.49%，
--      且并非随机缺失（匿名发票平均金额是实名的 1.89 倍、行数是 3.66 倍），
--      故本结论不能外推为"全体客户"。
--    · 本分析【不能】回答"该不该投入拉新" —— 判断拉新回报需要获客成本
--      与客户生命周期价值，本数据集均不包含。
--    · 本分析【不能】回答"头部客户稳不稳" —— 需要 D6 的留存 / 同期群分析，
--      观察头部客户是否持续复购。
--
-- ============================================================
-- 【另一条路：消费高有两种成因，运营动作不同】
--   · 高频复购型：14911（370 次）、12748（316 次）、18102（145 次）
--     → 长期稳定下单，像批发商  → 动作是"维护关系、防止流失"
--   · 单笔大额型：12415（仅 23 次，£143,214.52）、15098（仅 2 次，£39,619.50）
--     → 次数少但一次买很多      → 动作是"促成复购、提高下单频次"
--   两类客户在"消费额"这一个指标上看起来一样，但需要完全不同的运营手段。
--   仅看金额排名会把它们混在一起 —— 这是帕累托分析的固有盲区。
-- ============================================================
