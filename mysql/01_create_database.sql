-- ============================================================
-- 01_create_database.sql
-- 用途：创建项目数据库
-- ============================================================
-- 设计要点：
--   1) 字符集用 utf8mb4 而非 utf8。
--      MySQL 的 utf8 是残缺实现（仅 3 字节），存不了 emoji 与部分生僻字；
--      本数据集商品描述含 £ 符号，必须用 utf8mb4（真正的 4 字节 UTF-8）。
--   2) 排序规则 utf8mb4_0900_ai_ci：ai = 重音不敏感，ci = 大小写不敏感。
--      建库时定好，后续所有字符串比较、去重、排序都按它走。
--   3) IF NOT EXISTS 保证脚本幂等 —— 重复执行不报错、不改变任何东西。
-- ============================================================

CREATE DATABASE IF NOT EXISTS online_retail
  DEFAULT CHARACTER SET utf8mb4
  DEFAULT COLLATE utf8mb4_0900_ai_ci;

-- 设为当前默认库，后续语句无需再写库名前缀
USE online_retail;
