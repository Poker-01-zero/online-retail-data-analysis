-- ============================================================
-- 09_monthly_trend.sql
-- 用途：月度营收趋势（25 个月）+ 同比增长 + 季节性
-- 依赖：05（清洗层）、06（派生字段 Revenue / YearMonth）
-- 表：online_retail_clean
-- 产出：供 Tableau / Excel 画图的结果集
-- ============================================================
-- 【这份结果要回答三个问题】
--   1) 这门生意在增长吗？        → ② 年度汇总 + ③ 同比
--   2) 有没有淡旺季？            → ④ 季节性
--   3) 增长/下滑从哪里来？       → 订单数 与 AOV 谁在动
--
-- 【两条必须注意的口径】
--
--   1) 首末月不完整。数据覆盖 2009-12-01 ~ 2011-12-09：
--        · 2009-12 是【完整月】（数据自 12 月 1 日起）
--        · 2011-12 只有【9 天】（数据止于 12 月 9 日）
--      因此 2011-12 不可与完整月直接比较，做同比必须【统一剔除 12 月】。
--      查询中用「是否完整月」列显式标出，画图时也应在图上标注。
--
--   2) 本文件用【全量口径】营收（含匿名订单）—— 这是正确的，
--      因为"营收趋势"是经营指标，不应因为客户未知就把它排除。
--      ⚠️ 但若在本文件里加入"客户数"，那个数字只能是【实名口径】，
--         两者混在一张表里会误导。故本文件默认不输出客户数。
--
-- 【关键数字（2026-10-15 实测，修复取消订单漏洞后）】
--   总营收 £19,082,339.73 ｜ 25 个月 ｜ 39,231 张订单
--   2010 全年 £9,201,381.60 ｜ 2011 全年 £9,094,215.72  → 表面持平
--   1-11 月同比：营收 +2.56%，订单数 -3.53%，AOV +6.31%
--     → 营收"持平"是假象：订单量在掉，靠客单价上涨抵消
--   旺季：9-11 月，峰值 11 月（2010、2011 两年一致）
-- ============================================================

USE online_retail;


-- ------------------------------------------------------------
-- ① 月度明细（25 行）—— 画折线图的主表
--    「是否完整月」用数据动态判定，不写死月份：
--    最后一个自然月就是被数据截断的那个。
--    检查点：25 行 ｜ 营收合计 19082339.73
-- ------------------------------------------------------------
SELECT
  YearMonth                                   AS 月份,
  DATE_FORMAT(YearMonth, '%Y-%m')             AS 月份标签,      -- 画图用，字符串更好读
  COUNT(DISTINCT Invoice)                     AS 订单数,
  ROUND(SUM(Revenue), 2)                      AS 营收,
  ROUND(SUM(Revenue) / COUNT(DISTINCT Invoice), 2) AS AOV,
  CASE WHEN YearMonth = (SELECT MAX(DATE_FORMAT(InvoiceDate, '%Y-%m-01'))
                         FROM online_retail_clean)
       THEN '否（数据截断）' ELSE '是' END      AS 是否完整月
FROM online_retail_clean
GROUP BY YearMonth
ORDER BY YearMonth;


-- ------------------------------------------------------------
-- ② 年度汇总
--    ⚠️ 2009 只有 12 月一个月，不能与 2010 / 2011 的年度数字直接比较。
--    检查点：三年营收合计 19082339.73
-- ------------------------------------------------------------
SELECT
  Year                          AS 年,
  COUNT(DISTINCT Month)         AS 覆盖月数,
  COUNT(DISTINCT Invoice)       AS 订单数,
  ROUND(SUM(Revenue), 2)        AS 营收,
  ROUND(SUM(Revenue) / COUNT(DISTINCT Invoice), 2) AS AOV
FROM online_retail_clean
GROUP BY Year
ORDER BY Year;

-- 实测：2009 1个月 £786,742.41 ｜ 2010 12个月 £9,201,381.60 ｜ 2011 12个月 £9,094,215.72


-- ------------------------------------------------------------
-- ③ 同比增长（统一用 1-11 月口径）
--    为什么要剔 12 月：2011 的 12 月只有 9 天，含进去会凭空造出一个"暴跌"。
--    这一条是本文件最重要的一步 —— 不剔 12 月，结论就是错的。
-- ------------------------------------------------------------
SELECT
  Year                                                    AS 年,
  COUNT(DISTINCT Invoice)                                 AS 订单数,
  ROUND(SUM(Revenue), 2)                                  AS 营收,
  ROUND(SUM(Revenue) / COUNT(DISTINCT Invoice), 2)        AS AOV
FROM online_retail_clean
WHERE Month <> 12
GROUP BY Year
ORDER BY Year;

-- 实测：
--   2010  17,928 张  £8,433,001.86  AOV £470.38
--   2011  17,296 张  £8,649,244.30  AOV £500.07
--   同比    -3.53%        +2.56%         +6.31%
--   → 营收"持平"是假象：订单量在掉，靠客单价上涨抵消


-- ------------------------------------------------------------
-- ④ 季节性（跨年按月份合并）
--    把两年的同一个月份加起来，看业务本身的淡旺季规律。
--    ⚠️ 必须剔除被截断的 2011-12 —— 它只有 9 天，
--       混进来会把 12 月的"平均月营收"拉低，制造出假的年末下滑。
--    检查点：12 行；合计营收 = 19082339.73 − 444971.42 = 18637368.31
-- ------------------------------------------------------------
SELECT
  Month                             AS 月份,
  COUNT(DISTINCT Year)              AS 覆盖年数,
  ROUND(SUM(MonthlyRevenue), 2)     AS 合计营收,      -- 注意：取的是派生表的列
  ROUND(AVG(MonthlyRevenue), 2)     AS 平均月营收
FROM (
  SELECT Year, Month, YearMonth, SUM(Revenue) AS MonthlyRevenue
  FROM online_retail_clean
  WHERE YearMonth <> (SELECT MAX(DATE_FORMAT(InvoiceDate, '%Y-%m-01'))
                      FROM online_retail_clean)      -- 剔除数据截断的末月
  GROUP BY Year, Month, YearMonth
) t
GROUP BY Month
ORDER BY Month;

-- 实测（各月平均月营收，剔除了截断的 2011-12）：
--    1 月 £585,487 ｜  2 月 £516,433 ← 全年最低
--    3 月 £717,405 ｜  4 月 £570,357 ｜  5 月 £678,182 ｜  6 月 £706,811
--    7 月 £648,153 ｜  8 月 £687,193 ｜  9 月 £935,376 ← 旺季起点
--   10 月 £1,068,361 ｜ 11 月 £1,427,363 ← 峰值 ｜ 12 月 £777,561
--   → 9-11 月为旺季，11 月为峰值，两年规律一致 = 稳定的季节性
--
-- ⚠️ 一个细节：12 月的"覆盖年数"是 2，但它是 2009-12 + 2010-12
--    （2011-12 被剔除了），与其余月份的 2010+2011 不是同一组年份。
--    做严格的冬季对比时应留意这点。


-- ============================================================
-- 【分析结论】
-- ============================================================
--
-- 一、表面持平，实为"量跌价升"
--    2010 全年 £9,201,381.60，2011 全年 £9,094,215.72，看起来几乎没变。
--    但剔除不完整的 12 月后：营收 +2.56%，订单数 −3.53%，AOV +6.31%。
--    → 所以：总营收这一个数字会掩盖结构变化。若只看总额会以为业务很稳，
--      拆开才发现是靠客单价硬撑，而订单量在持续流失。
--
-- 二、稳定且可预期的旺季（这是本分析里最"可用"的结论）
--    9-11 月为旺季，11 月为两年共同的峰值（£1.41M / £1.44M）。
--    两年规律完全一致，说明这是业务的固有季节性，不是偶然波动。
--    → 所以：备货、客服排班、营销预算都应向 9-11 月倾斜；
--      而 1-2 月是全年低谷（2011-02 £504,743），适合做淡季维护而非冲量。
--
-- 三、边界声明
--    · 2011-12 只有 9 天，任何含它的同比都是错的 —— 本文件中已剔除。
--    · 本分析只有两年数据，无法判断"量跌价升"是趋势还是短期波动。
--      要下"增长停滞"的结论，至少需要 3 年以上数据。
--    · 2026-10 修复的"取消订单漏洞"对本文件影响显著：
--      2011-12 的营收因剔除一笔 £168,469.60 的假单，从 £614,487.63 降至 £444,971.42。
--      这也说明趋势分析前必须先保证清洗口径正确，否则错误会被放大成"趋势"。
-- ============================================================
