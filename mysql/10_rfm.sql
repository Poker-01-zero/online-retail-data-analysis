-- ============================================================
-- 10_rfm.sql
-- 用途：RFM 客户分群模型
-- 依赖：05（清洗层）、06（派生字段 Revenue）
-- 表：online_retail_clean
-- ============================================================
-- 【RFM 是什么】
--   给每个客户在三个维度上打分：
--     R (Recency)   最后一次购买距今多久  —— 越近越好
--     F (Frequency) 买了多少次            —— 越多越好
--     M (Monetary)  花了多少钱            —— 越多越好
--
--   三个维度【互相独立】，这才是它的价值：
--     客户 A 和客户 B 可能消费额完全相同（都是大客户），
--     但 A 最近还在买、B 已经半年没来 —— 一个要维护，一个要抢救。
--     光看消费额这一个数字，这两类人长得一模一样。
--
-- 【四个关键决策】
--
--   1) R 的基准日 = 【数据截止那一刻】，用 MAX(InvoiceDate) 动态取。
--      ❌ 不能用"今天"：数据止于 2011 年，用今天的日期会让所有客户的 R
--         都变成 5000 天左右，完全失去区分度。
--      ❌ 也不能用"最后一个完整月的月末"（2011-11-30）：
--         实测有 612 个客户（10.5%）的最后购买落在 12 月 1–9 日，
--         基准日往前挪会让这批人的 R 变成【负数】—— 而他们恰恰是最活跃的客户。
--      截断对所有人一视同仁，不该只对 12 月买过的人动手脚。
--
--   2) 分档用 NTILE(5) 等频分箱：每档人数相同（5835 / 5 = 1167 人）。
--      等频的优点是不受极端值影响；缺点是门槛会随样本变化。
--
--   3) ⚠️⚠️ 【NTILE 的分数方向 —— 本项目最容易错的一处】
--      NTILE 的分数是【从 1 开始、按排序顺序递增】的。
--      也就是说：排在最前面的拿 1 分，排在最后的拿 5 分。
--      所以要让"最好的"排在最后：
--        R 分：ORDER BY R DESC   （R 大 = 久没买 = 差 → 差在前 → 拿低分）
--        F 分：ORDER BY F ASC    （F 小 = 买得少 = 差 → 差在前 → 拿低分）
--        M 分：ORDER BY M ASC
--      反过来写，三个维度【全部倒置】，而且不会报任何错 ——
--      实测第一版就写反了，结果"一般挽留客户"成了营收占比 83% 的优质客群。
--
--   4) 只看实名客户（老规矩，`WHERE Customer_ID IS NOT NULL`）。
--
-- 【已知局限：并列值会被硬切】
--   NTILE 是【按人数】均分，遇到大量并列值时会强行切开。
--   本数据中 F=1 的客户有 1,609 人，远超一档的 1,167 人，
--   于是这批"完全一样"的客户被分到了不同档位。
--   若需要严格口径，应改用【等宽分档】（自己定阈值，如 F≥10 算高频）。
--   本文件保留 NTILE 是为了与"标准 RFM 做法"保持一致。
--
-- 【关键数字（2026-10-15 实测）】
--   客户数 5,835 ｜ R 平均 199.7 天 ｜ R 最大 738 天 ｜ R>365 天 2,421 人(41.5%)
--   重要价值客户 1,330 人（22.79%）→ 营收 69.76%
-- ============================================================

USE online_retail;


-- ------------------------------------------------------------
-- ① 地基：每个客户的 R / F / M 原始值
--    检查点：客户数 5835 ｜ F 合计 36309 ｜ M 合计 16508231.68
-- ------------------------------------------------------------
WITH c AS (
  SELECT
    Customer_ID,
    -- R：距数据截止日多少天。基准日动态取自数据本身，不写死日期。
    DATEDIFF((SELECT MAX(InvoiceDate) FROM online_retail_clean),
             MAX(InvoiceDate))            AS R,
    COUNT(DISTINCT Invoice)               AS F,
    SUM(Revenue)                          AS M
  FROM online_retail_clean
  WHERE Customer_ID IS NOT NULL
  GROUP BY Customer_ID
)
SELECT COUNT(*) AS 客户数, ROUND(AVG(R),1) AS 平均R, MAX(R) AS 最大R,
       SUM(R = 0) AS 最后一天买过的人数,
       SUM(R > 365) AS 超过一年没买的人数,
       SUM(F) AS F合计, ROUND(SUM(M),2) AS M合计
FROM c;


-- ------------------------------------------------------------
-- ② 打分：R / F / M 各打 1–5 分
--    ⚠️ 注意三个 ORDER BY 的方向，见文件头决策 3
-- ------------------------------------------------------------
WITH c AS (
  SELECT Customer_ID,
         DATEDIFF((SELECT MAX(InvoiceDate) FROM online_retail_clean),
                  MAX(InvoiceDate))       AS R,
         COUNT(DISTINCT Invoice)          AS F,
         SUM(Revenue)                     AS M
  FROM online_retail_clean
  WHERE Customer_ID IS NOT NULL
  GROUP BY Customer_ID
)
SELECT
  Customer_ID, R, F, ROUND(M, 2) AS M,
  NTILE(5) OVER (ORDER BY R DESC) AS R分,   -- 久没买的排前面 → 拿低分
  NTILE(5) OVER (ORDER BY F ASC)  AS F分,   -- 买得少的排前面 → 拿低分
  NTILE(5) OVER (ORDER BY M ASC)  AS M分    -- 花得少的排前面 → 拿低分
FROM c
ORDER BY R分 DESC, F分 DESC, M分 DESC
LIMIT 20;


-- ============================================================
-- ③ 八类客户 + 每类规模与营收贡献
--    高低的划分：分数 >= 4 算"高"（即前两档，覆盖前 40% 的客户）
-- ============================================================
WITH c AS (
  SELECT Customer_ID,
         DATEDIFF((SELECT MAX(InvoiceDate) FROM online_retail_clean),
                  MAX(InvoiceDate))       AS R,
         COUNT(DISTINCT Invoice)          AS F,
         SUM(Revenue)                     AS M
  FROM online_retail_clean
  WHERE Customer_ID IS NOT NULL
  GROUP BY Customer_ID
),
s AS (
  SELECT Customer_ID, R, F, M,
         NTILE(5) OVER (ORDER BY R DESC) AS r分,
         NTILE(5) OVER (ORDER BY F ASC)  AS f分,
         NTILE(5) OVER (ORDER BY M ASC)  AS m分
  FROM c
),
g AS (
  SELECT *,
    CASE
      WHEN r分 >= 4 AND f分 >= 4 AND m分 >= 4 THEN '1 重要价值客户'
      WHEN r分 <  4 AND f分 >= 4 AND m分 >= 4 THEN '2 重要保持客户'
      WHEN r分 >= 4 AND f分 <  4 AND m分 >= 4 THEN '3 重要发展客户'
      WHEN r分 <  4 AND f分 <  4 AND m分 >= 4 THEN '4 重要挽留客户'
      WHEN r分 >= 4 AND f分 >= 4 AND m分 <  4 THEN '5 一般价值客户'
      WHEN r分 <  4 AND f分 >= 4 AND m分 <  4 THEN '6 一般保持客户'
      WHEN r分 >= 4 AND f分 <  4 AND m分 <  4 THEN '7 一般发展客户'
      ELSE                                        '8 一般挽留客户'
    END AS 客户类型
  FROM s
)
SELECT
  客户类型,
  COUNT(*)                                          AS 客户数,
  ROUND(COUNT(*) / 5835 * 100, 2)                   AS 客户占比,
  ROUND(SUM(M), 2)                                  AS 营收,
  ROUND(SUM(M) / (SELECT SUM(M) FROM c) * 100, 2)   AS 营收占比,
  ROUND(AVG(R), 0)                                  AS 平均R天,
  ROUND(AVG(F), 1)                                  AS 平均F,
  ROUND(AVG(M), 0)                                  AS 平均M
FROM g
GROUP BY 客户类型
ORDER BY 营收 DESC;

-- 实测（检查点：客户数合计 5835 ｜ 营收合计 16508231.68）：
--
--  客户类型        客户数  客户占比  营收          营收占比  平均R天  平均F   平均M
--  1 重要价值客户   1330   22.79   11516673.32    69.76      19    16.4   8659
--  2 重要保持客户    598   10.25    2391184.34    14.48     181     9.5   3999
--  8 一般挽留客户   2421   41.49    1005772.43     6.09     364     1.7    415
--  4 重要挽留客户    317    5.43     730518.07     4.43     277     2.9   2304
--  7 一般发展客户    674   11.55     331356.64     2.01      26     1.9    492
--  5 一般价值客户    241    4.13     206432.91     1.25      23     5.2    857
--  3 重要发展客户     89    1.53     186975.97     1.13      25     2.6   2101
