-- ============================================================
-- 【分析结论】
-- ============================================================
--
-- 一、最重要的一类不是"重要价值客户"，而是"重要保持客户"
--
--    · 重要价值客户 1,330 人（22.79%）贡献 69.76% 营收 ——
--      平均 19 天前来过、买了 16.4 次 —— 这是健康的核心盘，要【保】。
--
--    · 重要保持客户 598 人（10.25%）贡献 14.48% 营收，
--      平均买了 9.5 次、消费 £3,999 —— 是标准的优质客户，
--      但【平均已经 181 天没来了】（半年）。
--    → 所以：这批人是最值得投入的抢救对象。他们有过高频高额的行为，
--      流失不是"没兴趣"，更可能是"被忘了"或"被竞品接走了"。
--      用一次唤醒触达的成本，远低于重新拉一个新客。
--
-- 二、低价值客群极大，但"放弃"要分类
--
--    · 一般挽留客户 2,421 人（41.49%）只贡献 6.09% 营收，
--      平均 R = 364 天（一年没来）、F = 1.7 —— 基本已经流失。
--    → 所以：这批人不应继续投入常规营销预算。
--
-- 三、本次 RFM 不能回答的问题（边界声明）
--
--    · 口径：仅【实名客户】。匿名订单行占 22.74%、营收占 13.49%，
--      且并非随机缺失，本结论不能外推为"全体客户"。
--    · RFM 是【静态快照】—— 它告诉你客户"现在处于什么状态"，
--      但回答不了"他们是怎么走到这个状态的"、以及"未来会怎样"。
--      这需要 D6 的第二部分：留存 / 同期群分析。
--    · NTILE 在并列值上会硬切（见文件头「已知局限」）。
-- ============================================================
