-- ============================================================
-- 02_create_raw_table.sql
-- 用途：创建原始层表 online_retail_raw（Raw Layer）
-- ============================================================
-- 设计原则：
--   1) 全部字段声明为 VARCHAR —— 原始层不做任何类型转换，原样接住数据。
--      原因：源数据 Customer_ID 存在 '13085.0' 这类浮点残留与大量空值，
--            若直接声明 INT，MySQL 会产生成千上万条截断警告，掩盖真正的错误。
--            类型转换推迟到清洗层处理（ELT 思想：先 Load，后 Transform）。
--   2) 字段宽度按【实测最大长度】设定并留安全余量，防止静默截断。
--      实测最大长度见各字段注释。
--   3) 不设主键、不建索引 —— 原始层含大量重复行（加主键会导入失败），
--      且无索引时批量导入最快（索引需每插一行就维护一次 B+ 树）。
-- ============================================================
-- 注意：表已存在时本脚本会报 Error 1050，这是预期的、无害的。
--       它只是告诉你"表已存在，无需重建"。如需重建，先手动执行：
--         DROP TABLE online_retail_raw;
--       再重新执行本脚本与 03_load_data.sql。
--       本脚本刻意不写 DROP TABLE，避免误执行导致数据丢失。
-- ============================================================

USE online_retail;

CREATE TABLE online_retail_raw (
  Invoice      VARCHAR(12),   -- 发票号，实测最大长度 7（取消单以 C 开头）
  StockCode    VARCHAR(15),   -- 商品编码，实测最大长度 12（5 位数字 + 可选字母后缀）
  Description  VARCHAR(100),  -- 商品描述，实测最大长度 35（含空值）
  Quantity     VARCHAR(10),   -- 数量，实测最大长度 6（负值表示退货）
  InvoiceDate  VARCHAR(25),   -- 下单时间，实测最大长度 19（格式 YYYY-MM-DD HH:MM:SS）
  Price        VARCHAR(15),   -- 单价，实测最大长度 9（可为负值：坏账冲销）
  Customer_ID  VARCHAR(15),   -- 客户 ID，实测最大长度 7（大量空值，约 22.8%）
  Country      VARCHAR(50)    -- 国家，实测最大长度 20
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
